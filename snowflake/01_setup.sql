-- Snowflake platform setup: roles, databases, and cost-controlled warehouses.
-- Compute is billed per second while a warehouse runs, so each workload gets its own
-- small warehouse with a 60-second auto-suspend and a resource monitor as a hard limit.

USE ROLE ACCOUNTADMIN;

-- Roles ---------------------------------------------------------------------------------
CREATE ROLE IF NOT EXISTS LOADER;        -- ingestion (COPY INTO from S3)
CREATE ROLE IF NOT EXISTS TRANSFORMER;   -- dbt
CREATE ROLE IF NOT EXISTS REPORTER;      -- Power BI / analysts (read-only on gold)
GRANT ROLE LOADER, TRANSFORMER, REPORTER TO ROLE SYSADMIN;

-- Databases -----------------------------------------------------------------------------
CREATE DATABASE IF NOT EXISTS RAW;
CREATE SCHEMA   IF NOT EXISTS RAW.BRONZE;
CREATE DATABASE IF NOT EXISTS ANALYTICS;      -- dbt creates SILVER and GOLD schemas here

-- Warehouses (one per workload) -----------------------------------------------------------
CREATE WAREHOUSE IF NOT EXISTS WH_LOAD
    WAREHOUSE_SIZE = XSMALL  AUTO_SUSPEND = 60  AUTO_RESUME = TRUE  INITIALLY_SUSPENDED = TRUE
    COMMENT = 'COPY INTO from the S3 bronze layer';

CREATE WAREHOUSE IF NOT EXISTS WH_TRANSFORM
    WAREHOUSE_SIZE = SMALL   AUTO_SUSPEND = 60  AUTO_RESUME = TRUE  INITIALLY_SUSPENDED = TRUE
    COMMENT = 'dbt transformations (silver/gold), daily batch window';

CREATE WAREHOUSE IF NOT EXISTS WH_BI
    WAREHOUSE_SIZE = XSMALL  AUTO_SUSPEND = 60  AUTO_RESUME = TRUE  INITIALLY_SUSPENDED = TRUE
    COMMENT = 'Power BI refreshes and ad-hoc analyst queries';

-- Resource monitors: notify at 80%, suspend at 100% of the monthly credit quota -----------
CREATE OR REPLACE RESOURCE MONITOR RM_LOAD_TRANSFORM WITH CREDIT_QUOTA = 60
    FREQUENCY = MONTHLY START_TIMESTAMP = IMMEDIATELY
    TRIGGERS ON 80 PERCENT DO NOTIFY
             ON 100 PERCENT DO SUSPEND;

CREATE OR REPLACE RESOURCE MONITOR RM_BI WITH CREDIT_QUOTA = 40
    FREQUENCY = MONTHLY START_TIMESTAMP = IMMEDIATELY
    TRIGGERS ON 80 PERCENT DO NOTIFY
             ON 100 PERCENT DO SUSPEND;

ALTER WAREHOUSE WH_LOAD      SET RESOURCE_MONITOR = RM_LOAD_TRANSFORM;
ALTER WAREHOUSE WH_TRANSFORM SET RESOURCE_MONITOR = RM_LOAD_TRANSFORM;
ALTER WAREHOUSE WH_BI        SET RESOURCE_MONITOR = RM_BI;

-- Grants ----------------------------------------------------------------------------------
GRANT USAGE ON WAREHOUSE WH_LOAD      TO ROLE LOADER;
GRANT USAGE ON WAREHOUSE WH_TRANSFORM TO ROLE TRANSFORMER;
GRANT USAGE ON WAREHOUSE WH_BI        TO ROLE REPORTER;

GRANT USAGE ON DATABASE RAW TO ROLE LOADER;
GRANT ALL   ON SCHEMA RAW.BRONZE TO ROLE LOADER;
GRANT USAGE ON DATABASE RAW TO ROLE TRANSFORMER;
GRANT USAGE ON SCHEMA RAW.BRONZE TO ROLE TRANSFORMER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA RAW.BRONZE TO ROLE TRANSFORMER;

GRANT ALL ON DATABASE ANALYTICS TO ROLE TRANSFORMER;
GRANT USAGE ON DATABASE ANALYTICS TO ROLE REPORTER;
GRANT USAGE ON FUTURE SCHEMAS IN DATABASE ANALYTICS TO ROLE REPORTER;
GRANT SELECT ON FUTURE TABLES IN DATABASE ANALYTICS TO ROLE REPORTER;
